#!/usr/bin/env python3
"""Measures, on the emulator itself, which Thomson key (matrix scancode, with or without Shift)
produces each ASCII character in BASIC 128, and writes frontend/typemap.h.

Method: in BASIC the script types   N REM QQQ<key>QQQ<key>...   for every scancode, halts, and reads the
stored program from RAM with `mem`: the REM text holds the character code the ROM really produced.
Usage:  tools/calibrate_typemap.py [--reuse DIR] [MODEL ...]      (default models: PC128 MO6; ~4 min each)
        --reuse DIR  decode the cal3_out_<MODEL>.txt files already in DIR instead of running the emulator
Needs a built frontend/theodore-fe and theodore_libretro.so (run from the repository root)."""
import json, os, re, subprocess, sys

FE = "frontend/theodore-fe"; CORE = "theodore_libretro.so"
# keys that would disturb the BASIC line editor: Shift, DEL, INS, arrows, BASIC, CAPS, RAZ, F1-F5, Return, CNT, ACC, STOP, space
EXCL = {0x04,0x07,0x08,0x09,0x0b,0x0c,0x0d,0x0e,0x0f,0x17,0x1e,0x1f,0x26,0x27,0x2e,0x2f,0x36,0x37,0x3e,0x3f}
SCS = [x for x in range(0x50) if x not in EXCL]
TESTS = [(x, m) for x in SCS for m in ("", "s")]
PER = 5

def build_script(model):
    sc = ["wait 250", "type 1", "wait 300"]          # both boot menus: 1 = BASIC 128
    ln = 10
    for i in range(0, len(TESTS), PER):
        if model == "MO6":                            # AZERTY: libretro 'a' types Q, ';' types M
            sc += ["type %d RE" % ln, "press 59", "press 32"]
        else:
            sc.append("type %d REM " % ln)
        ln += 10
        for x, m in TESTS[i:i + PER]:
            sc += ["press 97"] * 3 if model == "MO6" else ["type QQQ"]
            sc += ["scan %02X %s" % (x, m) if m else "scan %02X" % x, "scan 04"]
        sc += ["type \\n", "wait 40"]
    sc += ["wait 100", "halt"] + ["mem %04X 1000" % a for a in range(0, 0xA000, 0x1000)]
    return "\n".join(sc) + "\n"

def run(model, d):
    script = os.path.join(d, "cal_script_%s.txt" % model)
    open(script, "w").write(build_script(model))
    env = dict(os.environ, SDL_VIDEODRIVER="dummy", SDL_AUDIODRIVER="dummy")
    out = subprocess.run([FE, "--core", CORE, "--model", model, "--no-console", "--script", script,
                          "--frames", "90000", "--turbo"], capture_output=True, text=True, env=env).stdout
    open(os.path.join(d, "cal3_out_%s.txt" % model), "w").write(out)

def decode(model, d):
    out = open(os.path.join(d, "cal3_out_%s.txt" % model)).read()
    mem = bytearray(0xA000)
    for m in re.finditer(r"^([0-9A-F]{4}): ((?:[0-9A-F]{2} ){1,16})", out, re.M):
        a = int(m.group(1), 16); bs = bytes.fromhex(m.group(2).replace(" ", ""))
        mem[a:a + len(bs)] = bs
    img = bytes(mem); res = {}; ln = 10
    for i in range(0, len(TESTS), PER):
        grp = TESTS[i:i + PER]
        p = img.find(bytes([ln >> 8, ln & 255, 0x8c, 0x20]))
        if p >= 0:
            parts = img[p + 4:img.index(b"\x00", p + 4)].split(b"QQQ")[1:]
            if len(parts) == len(grp):
                for t, pp in zip(grp, parts):
                    res[t] = pp[:-1] if pp.endswith(b" ") else pp     # the space ends dead keys (accents)
        ln += 10
    return res

def table(res):
    """ASCII 32..126 -> (scancode, shift) or None. Letters: Caps Lock is on after reset, so both key states give
    capitals; with Caps Lock off (verified on PC128) the plain key gives lower case and Shift upper case."""
    inv = {}
    for (sc, m), b in sorted(res.items(), key=lambda kv: (kv[0][1] != "", kv[0][0])):   # prefer no Shift
        if len(b) == 1 and 32 <= b[0] < 127:
            inv.setdefault(chr(b[0]), (sc, 1 if m else 0))
    t = {32: (0x04, 0)}
    for c in range(33, 127):
        ch = chr(c)
        if ch.islower():
            sc = inv.get(ch.upper(), (None,))[0]
            t[c] = (sc, 0) if sc is not None else None
        elif ch.isupper():
            sc = inv.get(ch, (None,))[0]
            t[c] = (sc, 1) if sc is not None else None
        else:
            t[c] = inv.get(ch)
    return t

def emit(models):
    o = ["/* Generated by tools/calibrate_typemap.py from key presses measured on the emulator itself (BASIC 128).",
         "   ASCII 32..126 -> Thomson matrix scancode + Shift. sc = -1: no key produces the character.",
         "   Letters assume Caps Lock off (lower case = plain key, upper case = Shift); with Caps Lock on, as after reset,",
         "   both give capitals. Return is scancode 0x26 on every model. */",
         "typedef struct { signed char sc; unsigned char shift; } TypeKey;", ""]
    for name, t in models:
        o.append("static const TypeKey typemap_%s[95] =\n{" % name.lower())
        for c in range(32, 127):
            v = t[c]; ch = chr(c).replace("\\", "\\\\").replace("*/", "* /")
            o.append("  { %3d, %d }, /* %s */" % (v[0] if v else -1, v[1] if v else 0, ch if c != 32 else "space"))
        o.append("};\n")
    return "\n".join(o)

if __name__ == "__main__":
    a = sys.argv[1:]; reuse = None
    if a[:1] == ["--reuse"]: reuse = a[1]; a = a[2:]
    models = a or ["PC128", "MO6"]
    d = reuse or "."
    out = []
    for m in models:
        if reuse is None: run(m, d)
        t = table(decode(m, d)); out.append((m, t))
        print(m, "typable:", sum(1 for c in range(33, 127) if t[c]), "of 94; none:", "".join(chr(c) for c in range(33, 127) if not t[c]))
    open("frontend/typemap.h", "w").write(emit(out))
    print("wrote frontend/typemap.h")
